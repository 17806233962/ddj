// ============ 宠物种族 ============
// evolveLv = 成为该形态所需的最低等级
// type: 电(electric) 克 水(water)，水 克 草(grass)，草 克 电，倍率见 TYPE_CHART
const TYPE_CHART = {
  electric: { water: 1.5, grass: 0.667 },
  water:    { fire: 1.5, grass: 1.5, electric: 0.667 },
  grass:    { electric: 1.5, water: 0.667, fire: 0.667 },
  fire:     { grass: 1.5, water: 0.667 },
  light:    { dark: 1.5, electric: 0.667 },
  dark:     { light: 0.667, electric: 1.5 },
};
function typeMult(atkType, defType) {
  return (TYPE_CHART[atkType] && TYPE_CHART[atkType][defType]) || 1;
}

